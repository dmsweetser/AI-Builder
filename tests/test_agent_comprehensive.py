#!/usr/bin/env python3
"""Comprehensive agent test with llama-server."""

import sys
import os
import json
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

os.environ["CUSTOM_ENDPOINT_URL"] = "http://localhost:8080/v1/chat/completions"
os.environ["CUSTOM_MODEL_NAME"] = "qwen35b"
os.environ["AIB_MAX_STEPS"] = "15"
os.environ["AIB_MAX_TOOL_RESULT_LENGTH"] = "4000"
os.environ["AIB_MAX_CONTEXT_TOKENS"] = "0"
os.environ["AIB_MAX_OUTPUT_TOKENS"] = "1024"

from agent_engine.engine import AgentEngine

# Create a more complex test project
test_dir = '/tmp/aibuilder_comprehensive_test'
if os.path.exists(test_dir):
    import shutil
    shutil.rmtree(test_dir)

os.makedirs(os.path.join(test_dir, 'src'), exist_ok=True)
os.makedirs(os.path.join(test_dir, 'tests'), exist_ok=True)

# Create files
with open(os.path.join(test_dir, 'README.md'), 'w') as f:
    f.write('# Comprehensive Test Project\n\nThis is a test project.\n')

with open(os.path.join(test_dir, 'src', 'main.py'), 'w') as f:
    f.write('def greet(name):\n    return f"Hello, {name}!"\n\ndef main():\n    print(greet("World"))\n\nif __name__ == "__main__":\n    main()\n')

with open(os.path.join(test_dir, 'src', 'utils.py'), 'w') as f:
    f.write('def add(a, b):\n    return a + b\n\ndef multiply(a, b):\n    return a * b\n')

with open(os.path.join(test_dir, 'tests', 'test_main.py'), 'w') as f:
    f.write('import unittest\nfrom src.main import greet\n\nclass TestMain(unittest.TestCase):\n    def test_greet(self):\n        self.assertEqual(greet("Test"), "Hello, Test!")\n\nif __name__ == "__main__":\n    unittest.main()\n')

with open(os.path.join(test_dir, 'config.json'), 'w') as f:
    json.dump({"app_name": "test", "version": "1.0"}, f, indent=2)

print("Test project created:")
for root, dirs, files in os.walk(test_dir):
    level = root.replace(test_dir, '').count(os.sep)
    indent = '  ' * level
    print(f'{indent}{os.path.basename(root)}/')
    subindent = '  ' * (level + 1)
    for file in files:
        print(f'{subindent}{file}')

# Create engine
config = {
    "rootDirectory": test_dir,
    "instructions": """Complete the following tasks:
1. List all files in the project using list_directory
2. Read the content of src/main.py using read_file
3. Search for all Python files using search_files
4. Grep for the word 'def' using grep_code
5. Write a new file 'src/output.txt' with content 'Generated by agent'
6. Edit src/utils.py to add a new function 'divide(a, b)' that returns a / b
7. Delete the file 'config.json'
8. List the directory again to verify all changes""",
    "job_id": "comprehensive_test_" + str(int(time.time() * 1000)),
    "enabled_tools": ["list_directory", "search_files", "grep_code", "read_file", "write_file", "edit_file", "delete_file"]
}

output_dir = '/tmp/aibuilder_comprehensive_output'
os.makedirs(output_dir, exist_ok=True)

events = []
def on_event(ev):
    events.append(ev)

engine = AgentEngine(config, output_dir=output_dir, step_callback=on_event)
result = engine.run()

print(f"\n{'='*60}")
print(f"Status: {result.get('status', 'unknown')}")
print(f"Steps: {result.get('steps', 0)}")
print(f"Summary: {result.get('summary', '')[:300]}")
print(f"{'='*60}")

print(f"\nStep history:")
for step in result.get('step_history', []):
    tool = step.get('tool', '?')
    params = step.get('params', {})
    res = step.get('result', {})
    preview = ''
    if res.get('error'):
        preview = f"ERROR: {res['error']}"
    elif res.get('content'):
        preview = res['content'][:100]
    elif res.get('summary'):
        preview = res['summary'][:100]
    else:
        preview = '(no output)'
    print(f"  Step {step.get('step', '?')}: {tool}({json.dumps(params)[:60]}) -> {preview}")

# Verify final state
print(f"\n{'='*60}")
print("Verifying final state:")
print(f"{'='*60}")

# Check files
expected_files = ['README.md', 'src/main.py', 'src/utils.py', 'src/output.txt', 'tests/test_main.py']
missing = []
for f in expected_files:
    path = os.path.join(test_dir, f)
    if os.path.exists(path):
        print(f"  ✓ {f} exists")
    else:
        print(f"  ✗ {f} MISSING")
        missing.append(f)

# Check config.json was deleted
config_path = os.path.join(test_dir, 'config.json')
if not os.path.exists(config_path):
    print(f"  ✓ config.json deleted")
else:
    print(f"  ✗ config.json still exists")

# Check output.txt content
output_path = os.path.join(test_dir, 'src/output.txt')
if os.path.exists(output_path):
    with open(output_path, 'r') as f:
        content = f.read()
    if 'Generated by agent' in content:
        print(f"  ✓ output.txt has correct content")
    else:
        print(f"  ✗ output.txt has wrong content: {content[:50]}")

# Check utils.py has divide function
utils_path = os.path.join(test_dir, 'src/utils.py')
if os.path.exists(utils_path):
    with open(utils_path, 'r') as f:
        content = f.read()
    if 'def divide' in content:
        print(f"  ✓ utils.py has divide function")
    else:
        print(f"  ✗ utils.py missing divide function")

print(f"\n{'='*60}")
if not missing:
    print("ALL CHECKS PASSED ✓")
else:
    print(f"MISSING FILES: {missing}")
print(f"{'='*60}")
